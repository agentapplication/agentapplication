import { readFile, writeFile } from "node:fs/promises";
import { execFile } from "node:child_process";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { promisify } from "node:util";

const repositoryRoot = path.resolve(
  path.dirname(fileURLToPath(import.meta.url)),
  "..",
);
const docsRoot = path.join(repositoryRoot, "docs");
const outputPath = path.join(docsRoot, "llms-full.txt");
const checkOnly = process.argv.includes("--check");
const sourceRef = process.argv
  .find((argument) => argument.startsWith("--source-ref="))
  ?.slice("--source-ref=".length);
const run = promisify(execFile);

async function readSource(relativePath) {
  if (!sourceRef) {
    return readFile(path.join(repositoryRoot, relativePath), "utf8");
  }

  const { stdout } = await run(
    "git",
    ["show", `${sourceRef}:${relativePath}`],
    { cwd: repositoryRoot, encoding: "utf8", maxBuffer: 10 * 1024 * 1024 },
  );
  return stdout;
}

const config = JSON.parse(
  await readSource("docs/docs.json"),
);

function collectPages(value) {
  if (typeof value === "string") return [value];
  if (Array.isArray(value)) return value.flatMap(collectPages);
  if (!value || typeof value !== "object" || value.href) return [];

  if (Array.isArray(value.pages)) return collectPages(value.pages);

  for (const key of [
    "groups",
    "tabs",
    "anchors",
    "dropdowns",
    "versions",
    "languages",
  ]) {
    if (Array.isArray(value[key])) return collectPages(value[key]);
  }

  return [];
}

function unquote(value) {
  if (value.startsWith('"') && value.endsWith('"')) {
    return JSON.parse(value);
  }
  if (value.startsWith("'") && value.endsWith("'")) {
    return value.slice(1, -1);
  }
  return value;
}

function parsePage(source, pagePath) {
  const frontmatter = source.match(/^---\r?\n([\s\S]*?)\r?\n---\r?\n?/);
  if (!frontmatter) {
    throw new Error(`${pagePath}.mdx has no frontmatter`);
  }

  const metadata = {};
  for (const line of frontmatter[1].split(/\r?\n/)) {
    const match = line.match(/^([A-Za-z][\w-]*):\s*(.*)$/);
    if (match) metadata[match[1]] = unquote(match[2].trim());
  }

  if (!metadata.title) {
    throw new Error(`${pagePath}.mdx has no title`);
  }

  return {
    title: metadata.title,
    description: metadata.description,
    body: source.slice(frontmatter[0].length).trim(),
  };
}

const pagePaths = collectPages(config.navigation);
if (pagePaths.length === 0) {
  throw new Error("docs.json navigation contains no pages");
}

const duplicate = pagePaths.find(
  (pagePath, index) => pagePaths.indexOf(pagePath) !== index,
);
if (duplicate) {
  throw new Error(`docs.json lists ${duplicate} more than once`);
}

const sections = await Promise.all(
  pagePaths.map(async (pagePath) => {
    const source = await readSource(`docs/${pagePath}.mdx`);
    const page = parsePage(source, pagePath);
    const route = pagePath === "index" ? "/" : `/${pagePath}`;
    const lines = [
      `# ${page.title}`,
      `Source: https://agentapplication.io${route}`,
    ];

    if (page.description) lines.push("", page.description);
    if (page.body) lines.push("", page.body);

    return lines.join("\n");
  }),
);

const output = [
  "# Agent Applications",
  "",
  `> ${config.description}`,
  "",
  "<!-- Generated by scripts/generate-llms-full.mjs from docs.json navigation. -->",
  "",
  sections.join("\n\n\n"),
  "",
].join("\n");

if (checkOnly) {
  let current;
  try {
    current = await readFile(outputPath, "utf8");
  } catch {
    current = undefined;
  }

  if (current !== output) {
    console.error("docs/llms-full.txt is out of date. Run npm run generate:llms.");
    process.exitCode = 1;
  }
} else {
  await writeFile(outputPath, output);
  console.log(`Wrote ${path.relative(repositoryRoot, outputPath)}`);
}
